FIRST = "כמה כסף צריך כדי להתחיל להשקיע?"  # the series opens with the question beginners ask most


def order(cycle):
    """The shuffled order of the bank for one pass through it (0, 1, 2...). The same on every run."""
    idx = list(range(len(QUESTIONS)))
    random.Random(f"stocksisx-questions-{cycle}").shuffle(idx)
    if cycle == 0:
        first = next(i for i, q in enumerate(QUESTIONS) if q[0] == FIRST)
        idx.remove(first)
        idx.insert(0, first)
    return idx


def question(n):
    """(question, big, points) for episode n (1-based): a random question, no repeats within 100."""
    cycle, i = divmod(n - 1, len(QUESTIONS))
    return QUESTIONS[order(cycle)[i]]


def script(n):
    q, big, points = question(n)
    kicker = f"שאלה של היום · #{n}"
    slides = [{"kind": "question", "title": q, "big": big, "head": {"kicker": kicker},
               "narration": f"שאלה של היום: {q}"}]
    for heading, text in points:
        slides.append({"kind": "lesson", "title": heading, "text": text, "narration": f"{heading}. {text}"})
    when = cadence.next_label()
    slides.append({"kind": "outro", "title": f"{when}: שאלה חדשה",
                   "narration": f"{when} שאלה חדשה. יש לכם שאלה על שוק ההון? כתבו לנו בתגובות, ועקבו כדי לא לפספס."})
    for sl in slides:
        sl["narration"] = speak(sl["narration"])
    caption = (f"שאלה של היום: {q}\n"
               + " · ".join(p[0] for p in points) + "\n"
               + f"שאלה של היום · #{n} · ב-{SLOT}\n"
               + "יש לכם שאלה על שוק ההון? כתבו בתגובות 👇\n"
               + f"{DISCLAIMER}\n\n#שאלהשלהיום #שוקההון #מניות #השקעות #למתחילים")
    return {"slides": slides, "caption": caption, "number": n, "big": big}
