def episode(n):
    """Episode n (1-based) of the series; it loops when it runs out."""
    return EPISODES[(n - 1) % len(EPISODES)]


def script(n):
    ep = episode(n)
    slides = []
    for i, s in enumerate(ep["slides"]):
        if s[0] == "fact":
            slides.append({"kind": "fact", "title": ep["title"].replace("הידעת? ", ""), "big": s[1], "label": s[2],
                           "narration": s[3], "head": {"kicker": f"הידעת? · פרק {n}"} if i == 0 else {}})
        else:
            slides.append({"kind": "lesson", "title": s[1], "text": s[2], "visual": s[3] if len(s) > 3 else None,
                           "narration": f"{s[1]}. {s[2]}"})
    nxt = episode(n + 1)["title"].replace("הידעת? ", "")
    slides.append({"kind": "outro", "title": f"בפרק הבא: {nxt}",
                   "narration": f"בפרק הבא של הידעת: {nxt}. שלחו את זה לחבר שאוהב שוק ההון, ועקבו כדי לא לפספס."})
    caption = (f"{ep['title']}\n"
               + " · ".join(s[1] for s in ep["slides"] if s[0] == "point") + "\n"
               + f"הידעת? · פרק {n} · כל יום ב-12:30\n{DISCLAIMER}\n\n"
               + f"{ep['tag']} #הידעת #שוקההון #מניות #השקעות")
    return {"slides": slides, "caption": caption, "number": n}
